import AppKit
import Combine
import Foundation

enum ClipboardImportStrategy: Sendable, Equatable {
    case merge
    case replace
}

struct ClipboardStoreClock: Sendable {
    var now: @Sendable () -> Date
    var sleep: @Sendable (UInt64) async throws -> Void

    static let live = ClipboardStoreClock(
        now: { Date() },
        sleep: { try await Task.sleep(nanoseconds: $0) }
    )
}

@MainActor
final class ClipboardStore: ObservableObject {
    private enum DefaultsKey {
        static let historyLimit = "historyLimit"
        static let retentionPolicy = "retentionPolicy"
        static let keepPinnedOnClear = "keepPinnedOnClear"
        static let clearUnpinnedOnQuit = "clearUnpinnedOnQuit"
        static let monitoringEnabled = "monitoringEnabled"
        static let monitoringPausedUntil = "monitoringPausedUntil"
        static let directPasteEnabled = "directPasteEnabled"
    }

    private static let defaultHistoryLimit = 50
    private static let pollInterval: TimeInterval = 0.5
    private static let pruneInterval: TimeInterval = 15 * 60
    private static let backupCleanupErrorMessage =
        "Clipboard backups could not be deleted. Check the Data section in Settings."
    private static let ignoredPasteboardTypes: Set<NSPasteboard.PasteboardType> = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")
    ]

    private var historyPolicy: ClipboardHistoryPolicy {
        ClipboardHistoryPolicy(
            unpinnedLimit: historyLimit,
            retentionPolicy: retentionPolicy
        )
    }

    @Published private(set) var items: [ClipboardItem]
    @Published private(set) var historyLimit: Int
    @Published private(set) var retentionPolicy: ClipboardRetentionPolicy
    @Published var keepPinnedOnClear: Bool {
        didSet {
            defaults.set(keepPinnedOnClear, forKey: DefaultsKey.keepPinnedOnClear)
        }
    }
    @Published var clearUnpinnedOnQuit: Bool {
        didSet {
            defaults.set(clearUnpinnedOnQuit, forKey: DefaultsKey.clearUnpinnedOnQuit)
        }
    }
    @Published var directPasteEnabled: Bool {
        didSet {
            defaults.set(directPasteEnabled, forKey: DefaultsKey.directPasteEnabled)
        }
    }
    @Published private(set) var isMonitoringEnabled: Bool {
        didSet {
            defaults.set(isMonitoringEnabled, forKey: DefaultsKey.monitoringEnabled)
            if isMonitoringEnabled {
                lastPasteboardChangeCount = pasteboard.changeCount
                startMonitoring()
            } else {
                stopMonitoring()
            }
        }
    }
    @Published private(set) var monitoringPausedUntil: Date?
    @Published private(set) var ignoredApplications: [ClipboardSourceApplication]
    @Published private(set) var lastCopiedID: ClipboardItem.ID?
    @Published private(set) var storageErrorMessage: String?
    @Published private(set) var captureWarning: String?
    @Published private(set) var pasteboardWriteWarning: String?
    @Published private(set) var backupInventory: ClipboardBackupInventory
    private let pasteboard: any ClipboardStorePasteboard
    private let storage: any ClipboardStoreRepository
    private let defaults: UserDefaults
    private let ignoredApplicationStore: ClipboardIgnoredApplicationStore
    private let sourceApplicationProvider: () -> ClipboardSourceApplication?
    private let usesWorkspaceSourceTracking: Bool
    private var lastPasteboardChangeCount: Int
    private var lastActiveApplication: ClipboardSourceApplication?
    private var persistenceBlockedByLoadFailure: Bool
    private var persistenceLoadFailureMessage: String?
    nonisolated(unsafe) private var workspaceActivationObserver: NotificationObserverToken?
    private var clearCopiedIndicatorTask: Task<Void, Never>?
    private let persistenceCoordinator: ClipboardPersistenceCoordinator
    private let imageCaptureQueue: ClipboardImageCaptureQueue
    private let pasteboardWriter: any ClipboardPasteboardWriting
    private let dragProviderFactory: ClipboardDragProviderFactory
    private let transferCoordinator: ClipboardStoreTransferCoordinator
    private let clock: ClipboardStoreClock
    private let monitoringSchedule: ClipboardMonitoringSchedule
    private var thumbnailCache = ClipboardThumbnailCache()
    private let thumbnailLoader: @Sendable (ClipboardItem) -> ClipboardThumbnailResult?
    private var transferObservation: AnyCancellable? = nil
    private var exportLimitWarningMessage: String?

    var isTransferBusy: Bool { transferCoordinator.isBusy }
    var transferProgressText: String? { transferCoordinator.progressText }

    var storageLocation: URL {
        storage.fileURL
    }

    var backupLocation: URL {
        storage.fileURL.deletingLastPathComponent()
    }

    func cachedThumbnailData(for item: ClipboardItem) -> Data? {
        switch thumbnailCache.lookup(for: item, now: clock.now()) {
        case let .data(data):
            return data
        case .unavailable:
            return nil
        case let .load(load):
            let thumbnailLoader = thumbnailLoader
            let expectedContentHash = item.image?.contentHash
            let expectedFileName = item.image?.fileName
            Task { @MainActor [weak self] in
                let result = await Task.detached(priority: .utility) {
                    thumbnailLoader(item)
                }.value
                guard let self else { return }
                guard let result,
                      let itemIndex = self.items.firstIndex(where: { $0.id == item.id }),
                      self.items[itemIndex].image?.contentHash == expectedContentHash,
                      self.items[itemIndex].image?.fileName == expectedFileName else {
                    self.thumbnailCache.finishLoading(
                        id: item.id,
                        load: load,
                        data: nil,
                        now: self.clock.now()
                    )
                    if result != nil {
                        self.persist()
                    }
                    return
                }
                if self.items[itemIndex].image?.thumbnailFileName != result.fileName {
                    self.items[itemIndex].image?.thumbnailFileName = result.fileName
                    self.items[itemIndex].image?.thumbnailData = nil
                    self.persist()
                }
                self.thumbnailCache.finishLoading(
                    id: item.id,
                    load: load,
                    data: result.data,
                    now: self.clock.now()
                )
                self.objectWillChange.send()
            }
        }
        return nil
    }

    var historySummaryText: String {
        let unpinnedCount = items.filter { !$0.isPinned }.count
        let pinnedCount = items.count - unpinnedCount

        if pinnedCount > 0 {
            return "\(unpinnedCount)/\(historyLimit) unpinned + \(pinnedCount) pinned"
        }

        return "\(unpinnedCount)/\(historyLimit) unpinned"
    }

    var monitoringStatusText: String {
        ClipboardMonitoringPreferences.statusText(
            isEnabled: isMonitoringEnabled,
            pausedUntil: monitoringPausedUntil,
            now: clock.now()
        )
    }

    init(
        pasteboard: any ClipboardStorePasteboard = NSPasteboard.general,
        storage: any ClipboardStoreRepository = ClipboardStorage(),
        defaults: UserDefaults = .standard,
        sourceApplicationProvider: (() -> ClipboardSourceApplication?)? = nil,
        imageProcessor: any ClipboardImageProcessing = ClipboardImageProcessingService(),
        pasteboardWriter: (any ClipboardPasteboardWriting)? = nil,
        thumbnailLoader: (@Sendable (ClipboardItem) -> ClipboardThumbnailResult?)? = nil,
        clock: ClipboardStoreClock = .live
    ) {
        let loadResult = storage.loadResult()
        let ignoredApplicationStore = ClipboardIgnoredApplicationStore(defaults: defaults)
        ClipboardDefaultExclusionsSeeder.seedIfNeeded(
            defaults: defaults,
            store: ignoredApplicationStore
        )
        self.pasteboard = pasteboard
        self.storage = storage
        self.defaults = defaults
        self.ignoredApplicationStore = ignoredApplicationStore
        self.imageCaptureQueue = ClipboardImageCaptureQueue(processor: imageProcessor)
        self.pasteboardWriter = pasteboardWriter ?? SystemClipboardPasteboardWriter(
            pasteboard: pasteboard
        )
        self.dragProviderFactory = ClipboardDragProviderFactory(imageReader: storage)
        let persistenceCoordinator = ClipboardPersistenceCoordinator(storage: storage)
        self.persistenceCoordinator = persistenceCoordinator
        self.transferCoordinator = ClipboardStoreTransferCoordinator(
            transferService: ClipboardTransferService(storage: storage),
            persistenceCoordinator: persistenceCoordinator
        )
        self.clock = clock
        self.monitoringSchedule = ClipboardMonitoringSchedule(clock: clock)
        self.thumbnailLoader = thumbnailLoader ?? { storage.thumbnailDataRepairingIfNeeded(for: $0) }
        self.backupInventory = (try? storage.backupInventory()) ?? .empty
        let usesSystemPasteboard = pasteboard is NSPasteboard
        self.sourceApplicationProvider = sourceApplicationProvider
            ?? (usesSystemPasteboard ? ClipboardSourceApplication.frontmost : { nil })
        self.usesWorkspaceSourceTracking = sourceApplicationProvider == nil && usesSystemPasteboard
        self.lastActiveApplication = usesWorkspaceSourceTracking
            ? ClipboardSourceApplication.frontmost()
            : nil
        switch loadResult {
        case let .success(loadedItems):
            self.items = loadedItems.sorted { $0.lastCopiedAt > $1.lastCopiedAt }
            self.storageErrorMessage = nil
            self.persistenceBlockedByLoadFailure = false
            self.persistenceLoadFailureMessage = nil
        case let .failure(error):
            self.items = []
            self.storageErrorMessage = error.localizedDescription
            self.persistenceBlockedByLoadFailure = true
            self.persistenceLoadFailureMessage = error.localizedDescription
        }
        self.captureWarning = nil
        let storedHistoryLimit = defaults.object(forKey: DefaultsKey.historyLimit) as? Int
            ?? Self.defaultHistoryLimit
        let normalizedHistoryLimit = min(max(storedHistoryLimit, 10), 200)
        self.historyLimit = normalizedHistoryLimit
        if storedHistoryLimit != normalizedHistoryLimit {
            defaults.set(normalizedHistoryLimit, forKey: DefaultsKey.historyLimit)
        }
        self.retentionPolicy = defaults.string(forKey: DefaultsKey.retentionPolicy)
            .flatMap(ClipboardRetentionPolicy.init(rawValue:))
            ?? .sevenDays
        self.keepPinnedOnClear = defaults.object(forKey: DefaultsKey.keepPinnedOnClear) as? Bool
            ?? true
        self.clearUnpinnedOnQuit = defaults.object(forKey: DefaultsKey.clearUnpinnedOnQuit) as? Bool
            ?? false
        self.directPasteEnabled = defaults.object(forKey: DefaultsKey.directPasteEnabled) as? Bool
            ?? false
        self.ignoredApplications = ignoredApplicationStore.load()
        let monitoringState = ClipboardMonitoringPreferences.initialState(
            defaults: defaults,
            now: clock.now()
        )
        self.monitoringPausedUntil = monitoringState.pausedUntil
        self.isMonitoringEnabled = monitoringState.isEnabled
        self.lastPasteboardChangeCount = pasteboard.changeCount
        self.transferObservation = transferCoordinator.objectWillChange.sink { [weak self] in
            self?.objectWillChange.send()
        }

        let oldItems = items
        pruneHistory()
        if items != oldItems {
            persist()
        }
        if isMonitoringEnabled {
            startMonitoring()
        }
        scheduleMonitoringResumeIfNeeded()
        startPeriodicPruning()
        installWorkspaceSourceTrackingIfNeeded()
    }

    deinit {
        clearCopiedIndicatorTask?.cancel()
        persistenceCoordinator.invalidateScheduledSave()
        if let workspaceActivationObserver {
            NSWorkspace.shared.notificationCenter.removeObserver(workspaceActivationObserver.value)
        }
    }

    func visibleItems(matching query: String, filter: ClipboardContentFilter = .all) -> [ClipboardItem] {
        let filteredItems = items.filter { filter.matches($0) }
        let searchQuery = ClipboardSearchQuery(query)
        return filteredItems.filter(searchQuery.matches)
    }

    func setHistoryLimit(_ limit: Int) {
        guard !isTransferBusy else { return }
        let normalizedLimit = min(max(limit, 10), 200)
        guard normalizedLimit != historyLimit else { return }
        historyLimit = normalizedLimit
        defaults.set(historyLimit, forKey: DefaultsKey.historyLimit)
        pruneHistory()
        persist()
    }

    func setRetentionPolicy(_ policy: ClipboardRetentionPolicy) {
        guard !isTransferBusy, policy != retentionPolicy else { return }
        retentionPolicy = policy
        defaults.set(retentionPolicy.rawValue, forKey: DefaultsKey.retentionPolicy)
        pruneHistory()
        persist()
    }

    func prospectiveDeletionCount(
        historyLimit proposedHistoryLimit: Int? = nil,
        retentionPolicy proposedRetentionPolicy: ClipboardRetentionPolicy? = nil,
        now: Date? = nil
    ) -> Int {
        let proposedPolicy = ClipboardHistoryPolicy(
            unpinnedLimit: min(max(proposedHistoryLimit ?? historyLimit, 10), 200),
            retentionPolicy: proposedRetentionPolicy ?? retentionPolicy
        )
        let result = ClipboardHistoryRules.applyingPolicy(
            to: items,
            policy: proposedPolicy,
            now: now ?? clock.now()
        )
        return result.expiredCount + result.overLimitCount
    }

    func setMonitoringEnabled(_ enabled: Bool) {
        clearMonitoringPause()
        if !enabled {
            invalidatePendingImageCaptures()
        }
        isMonitoringEnabled = enabled
    }

    func pauseMonitoring(for duration: ClipboardPauseDuration) {
        let until = duration.resumeDate(from: clock.now())
        monitoringPausedUntil = until
        defaults.set(until, forKey: DefaultsKey.monitoringPausedUntil)
        invalidatePendingImageCaptures()
        isMonitoringEnabled = false
        scheduleMonitoringResumeIfNeeded()
    }

    func addIgnoredApplication(_ application: ClipboardSourceApplication) {
        if let ownBundleIdentifier = Bundle.main.bundleIdentifier,
           application.bundleIdentifier == ownBundleIdentifier {
            return
        }

        guard !ignoredApplications.contains(where: { $0.bundleIdentifier == application.bundleIdentifier }) else {
            return
        }

        ignoredApplications.append(application)
        ignoredApplications.sort { $0.name.localizedCaseInsensitiveCompare($1.name) == .orderedAscending }
        persistIgnoredApplications()
    }

    func removeIgnoredApplication(_ application: ClipboardSourceApplication) {
        ignoredApplications.removeAll { $0.bundleIdentifier == application.bundleIdentifier }
        persistIgnoredApplications()
    }

    func isApplicationIgnored(_ application: ClipboardSourceApplication?) -> Bool {
        guard let application else {
            return false
        }

        return ignoredApplications.contains { $0.bundleIdentifier == application.bundleIdentifier }
    }

    func exportHistoryAsync(to url: URL) async throws {
        defer {
            discardPasteboardChangesObservedDuringTransfer()
        }
        try await transferCoordinator.export(items, to: url)
    }

