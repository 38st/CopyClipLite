enum ClipboardImportStrategy: Sendable, Equatable {
    case merge
    case replace
}

private final class PersistenceGeneration: @unchecked Sendable {
    private let lock = NSLock()
    private var value: UInt64 = 0

    func advance() -> UInt64 {
        lock.lock()
        defer { lock.unlock() }
        value &+= 1
        return value
    }

    func isCurrent(_ generation: UInt64) -> Bool {
        lock.lock()
        defer { lock.unlock() }
        return value == generation
    }
}

private final class ImportCancellationState: @unchecked Sendable {
    private let lock = NSLock()
    private var cancelled = false

    func cancel() {
        lock.lock()
        cancelled = true
        lock.unlock()
    }

    func checkCancellation() throws {
        lock.lock()
        let isCancelled = cancelled
        lock.unlock()
        if isCancelled {
            throw CancellationError()
        }
    }
}

struct ClipboardStoreClock: Sendable {
    var now: @Sendable () -> Date
    var sleep: @Sendable (UInt64) async throws -> Void

    static let live = ClipboardStoreClock(
        now: { Date() },
        sleep: { try await Task.sleep(nanoseconds: $0) }
    )
}

