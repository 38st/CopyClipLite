    private func pruneHistory(now: Date? = nil) {
        let now = now ?? clock.now()
        removeExpiredUnpinnedItems(now: now)
        trimToLimit()
    }

    private func pruneHistoryAndPersistIfNeeded(now: Date? = nil) {
        guard !isTransferBusy else { return }
        let now = now ?? clock.now()
        let oldItems = items

        pruneHistory(now: now)

        if items != oldItems {
            persist()
        }
    }

    private func removeExpiredUnpinnedItems(now: Date) {
        guard let expirationInterval = retentionPolicy.expirationInterval else {
            return
        }

        let cutoffDate = now.addingTimeInterval(-expirationInterval)
        items.removeAll { item in
            !item.isPinned && item.lastCopiedAt < cutoffDate
        }
    }

    private func trimToLimit() {
        var unpinnedCount = 0
        items.removeAll { item in
            if item.isPinned {
                return false
            }
            unpinnedCount += 1
            return unpinnedCount > historyLimit
        }
    }

    private func persist() {
        persistWorkItem?.cancel()
        let generation = persistenceGeneration.advance()
        let snapshot = items
        let storageRef = storage
        let persistenceGeneration = persistenceGeneration
        let workItem = DispatchWorkItem { [weak self] in
            guard persistenceGeneration.isCurrent(generation) else {
                return
            }
            do {
                let persistedItems = try storageRef.saveValidated(snapshot)
                DispatchQueue.main.async {
                    guard persistenceGeneration.isCurrent(generation) else {
                        return
                    }
                    self?.applyPersistedImageReferences(persistedItems)
                    self?.storageErrorMessage = nil
                }
            } catch {
                DispatchQueue.main.async {
                    self?.storageErrorMessage = error.localizedDescription
                }
            }
        }
        persistWorkItem = workItem
        persistenceQueue.asyncAfter(deadline: .now() + 0.15, execute: workItem)
    }

    @discardableResult
    func flushPendingPersist() -> Bool {
        invalidatePendingPersist()
        let snapshot = items
        do {
            let persistedItems = try persistenceQueue.sync {
                try storage.saveValidated(snapshot)
            }
            applyPersistedImageReferences(persistedItems)
            storageErrorMessage = nil
            return true
        } catch {
            storageErrorMessage = error.localizedDescription
            return false
        }
    }

    private func invalidatePendingPersist() {
        persistWorkItem?.cancel()
        persistWorkItem = nil
        _ = persistenceGeneration.advance()
    }

    private func applyPersistedImageReferences(_ persistedItems: [ClipboardItem]) {
        let persistedByID = Dictionary(uniqueKeysWithValues: persistedItems.map { ($0.id, $0) })
        var updatedItems = items
        var didChange = false

        for index in updatedItems.indices {
            guard let currentImage = updatedItems[index].image,
                  let persistedImage = persistedByID[updatedItems[index].id]?.image,
                  currentImage.contentHash == persistedImage.contentHash,
                  currentImage != persistedImage else {
                continue
            }

            updatedItems[index].image = persistedImage
            didChange = true
        }

        if didChange {
            items = updatedItems
        }
    }

    func dismissStorageError() {
        storageErrorMessage = nil
    }

    func dismissCaptureWarning() {
        captureWarning = nil
    }

    private func mergedItems(existing: [ClipboardItem], imported: [ClipboardItem]) -> [ClipboardItem] {
        var result = existing

        for importedItem in imported {
            let matchingIndex = result.firstIndex { existingItem in
                if existingItem.id == importedItem.id { return true }
                guard existingItem.contentKind == importedItem.contentKind else { return false }
                switch importedItem.contentKind {
                case .text:
                    return existingItem.text == importedItem.text
                case .image:
                    guard let importedHash = importedItem.image?.contentHash else { return false }
                    return existingItem.image?.contentHash == importedHash
                }
            }

            if let matchingIndex {
                var preferred = result[matchingIndex].lastCopiedAt >= importedItem.lastCopiedAt
                    ? result[matchingIndex]
                    : importedItem
                preferred.isPinned = result[matchingIndex].isPinned || importedItem.isPinned
                preferred.copyCount = max(result[matchingIndex].copyCount, importedItem.copyCount)
                result[matchingIndex] = preferred
            } else {
                result.append(importedItem)
            }
        }

        return result.sorted { $0.lastCopiedAt > $1.lastCopiedAt }
    }

    private func importCandidate(
        beforePruning: [ClipboardItem],
        sourceItemCount: Int,
        addedCount: Int,
        strategy: ClipboardImportStrategy,
        now: Date
    ) -> (items: [ClipboardItem], projection: ClipboardImportProjection) {
        let afterExpiration = itemsAfterExpiration(beforePruning, now: now)
        let finalItems = itemsAfterLimit(afterExpiration)
        return (
            finalItems,
            ClipboardImportProjection(
                strategy: strategy,
                sourceItemCount: sourceItemCount,
                addedCount: addedCount,
                deduplicatedCount: strategy == .merge
                    ? max(sourceItemCount - addedCount, 0)
                    : 0,
                expiredCount: beforePruning.count - afterExpiration.count,
                overLimitCount: afterExpiration.count - finalItems.count,
                retainedPinnedCount: finalItems.filter(\.isPinned).count,
                finalCount: finalItems.count
            )
        )
    }

    private func commitImportOnPersistenceQueue(
        currentItems: [ClipboardItem],
        candidateItems: [ClipboardItem]
    ) async throws -> ClipboardImportCommit {
        let cancellationState = ImportCancellationState()
        let storage = storage

        return try await withTaskCancellationHandler {
            try await withCheckedThrowingContinuation { continuation in
                persistenceQueue.async {
                    do {
                        try cancellationState.checkCancellation()
                        try storage.saveValidated(currentItems)
                        let backupURL = try storage.backup(
                            currentItems,
                            reason: "pre-import"
                        )
                        try cancellationState.checkCancellation()
                        try storage.saveValidated(candidateItems)
                        let loadedItems = try storage.loadResult().get().sorted {
                            $0.lastCopiedAt > $1.lastCopiedAt
                        }
                        continuation.resume(
                            returning: ClipboardImportCommit(
                                backupURL: backupURL,
                                items: loadedItems
                            )
                        )
                    } catch {
                        continuation.resume(throwing: error)
                    }
                }
            }
        } onCancel: {
            cancellationState.cancel()
        }
    }

    private func prunedItems(_ candidateItems: [ClipboardItem], now: Date? = nil) -> [ClipboardItem] {
        let now = now ?? clock.now()
        return itemsAfterLimit(itemsAfterExpiration(candidateItems, now: now))
    }

    private func itemsAfterExpiration(
        _ candidateItems: [ClipboardItem],
        now: Date
    ) -> [ClipboardItem] {
        var result = candidateItems.sorted { $0.lastCopiedAt > $1.lastCopiedAt }
        if let expirationInterval = retentionPolicy.expirationInterval {
            let cutoffDate = now.addingTimeInterval(-expirationInterval)
            result.removeAll { !$0.isPinned && $0.lastCopiedAt < cutoffDate }
        }
        return result
    }

    private func itemsAfterLimit(_ candidateItems: [ClipboardItem]) -> [ClipboardItem] {
        var result = candidateItems
        var unpinnedCount = 0
        result.removeAll { item in
            guard !item.isPinned else { return false }
            unpinnedCount += 1
            return unpinnedCount > historyLimit
        }
        return result
    }

    private func clearCopiedIndicator(after id: ClipboardItem.ID) {
        clearCopiedIndicatorTask?.cancel()
        clearCopiedIndicatorTask = Task { @MainActor [weak self] in
            guard let self else { return }
            try? await self.clock.sleep(1_200_000_000)
            guard !Task.isCancelled else { return }
            guard self.lastCopiedID == id else { return }
            self.lastCopiedID = nil
        }
    }
