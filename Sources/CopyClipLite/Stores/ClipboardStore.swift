    func dragItemProvider(for item: ClipboardItem) -> NSItemProvider {
        switch item.contentKind {
        case .text:
            let provider = NSItemProvider(object: item.text as NSString)
            provider.suggestedName = "CopyClip Text"
            if let rtfData = item.rtfData {
                provider.registerDataRepresentation(
                    forTypeIdentifier: UTType.rtf.identifier,
                    visibility: .all
                ) { completion in
                    completion(rtfData, nil)
                    return nil
                }
            }
            if let htmlData = item.htmlData {
                provider.registerDataRepresentation(
                    forTypeIdentifier: UTType.html.identifier,
                    visibility: .all
                ) { completion in
                    completion(htmlData, nil)
                    return nil
                }
            }
            return provider
        case .image:
            let provider = NSItemProvider()
            provider.suggestedName = "CopyClip Image.png"
            let storage = storage
            provider.registerDataRepresentation(
                forTypeIdentifier: UTType.png.identifier,
                visibility: .all
            ) { completion in
                let data = storage.imageData(for: item)
                completion(data, data == nil ? ClipboardStorageError.missingImageData : nil)
                return nil
            }
            provider.registerFileRepresentation(
                forTypeIdentifier: UTType.png.identifier,
                fileOptions: [],
                visibility: .all
            ) { completion in
                guard let data = storage.imageData(for: item) else {
                    completion(nil, false, ClipboardStorageError.missingImageData)
                    return nil
                }
                do {
                    let directory = FileManager.default.temporaryDirectory
                        .appendingPathComponent("CopyClipLite-Drag", isDirectory: true)
                    try FileManager.default.createDirectory(
                        at: directory,
                        withIntermediateDirectories: true
                    )
                    let url = directory.appendingPathComponent(
                        "\(item.id.uuidString)-CopyClip-Image.png"
                    )
                    try data.write(to: url, options: [.atomic])
                    completion(url, false, nil)
                } catch {
                    completion(nil, false, error)
                }
                return nil
            }
            return provider
        }
    }

    func importProjection(
        for artifact: ClipboardImportArtifact,
        strategy: ClipboardImportStrategy,
        now: Date? = nil
    ) -> ClipboardImportProjection {
        importPlan(for: artifact, now: now).projection(for: strategy)
    }

    func importPlan(
        for artifact: ClipboardImportArtifact,
        now: Date? = nil
    ) -> ClipboardImportPlan {
        let now = now ?? clock.now()
        let currentItems = items
        let mergeBeforePruning = mergedItems(
            existing: currentItems,
            imported: artifact.items
        )
        let replaceBeforePruning = artifact.items.sorted {
            $0.lastCopiedAt > $1.lastCopiedAt
        }
        let merge = importCandidate(
            beforePruning: mergeBeforePruning,
            sourceItemCount: artifact.items.count,
            addedCount: max(mergeBeforePruning.count - currentItems.count, 0),
            strategy: .merge,
            now: now
        )
        let replace = importCandidate(
            beforePruning: replaceBeforePruning,
            sourceItemCount: artifact.items.count,
            addedCount: artifact.items.count,
            strategy: .replace,
            now: now
        )
        return ClipboardImportPlan(
            artifact: artifact,
            currentItems: currentItems,
            historyLimit: historyLimit,
            retentionPolicy: retentionPolicy,
            mergeItems: merge.items,
            mergeProjection: merge.projection,
            replaceItems: replace.items,
            replaceProjection: replace.projection
        )
    }

    @discardableResult
    func importHistory(
        artifact: ClipboardImportArtifact,
        strategy: ClipboardImportStrategy
    ) async throws -> ClipboardImportCommit {
        try await importHistory(
            plan: importPlan(for: artifact),
            strategy: strategy
        )
    }

    @discardableResult
    func importHistory(
        plan: ClipboardImportPlan,
        strategy: ClipboardImportStrategy
    ) async throws -> ClipboardImportCommit {
        guard !isTransferBusy else {
            throw ClipboardStorageError.persistenceFailed
        }
        guard items == plan.currentItems,
              historyLimit == plan.historyLimit,
              retentionPolicy == plan.retentionPolicy else {
            throw ClipboardStorageError.importPlanExpired
        }

        isTransferBusy = true
        transferProgressText = "Applying import…"
        invalidatePendingImageCaptures()
        invalidatePendingPersist()
        stopMonitoring()
        defer {
            isTransferBusy = false
            transferProgressText = nil
            if isMonitoringEnabled {
                startMonitoring()
            }
        }

        let commit = try await commitImportOnPersistenceQueue(
            currentItems: plan.currentItems,
            candidateItems: plan.candidateItems(for: strategy)
        )
        items = commit.items
        storageErrorMessage = nil
        return commit
    }

    @discardableResult
    func importHistory(from url: URL, strategy: ClipboardImportStrategy) throws -> URL {
        let importedItems = try storage.importItems(from: url)
        var candidateItems: [ClipboardItem]

        switch strategy {
        case .merge:
            candidateItems = mergedItems(existing: items, imported: importedItems)
        case .replace:
            invalidatePendingImageCaptures()
            candidateItems = importedItems
        }

        candidateItems = prunedItems(candidateItems)
        invalidatePendingPersist()
        let currentItems = items
        let transactionResult = try persistenceQueue.sync {
            try storage.saveValidated(currentItems)
            let backupURL = try storage.backup(currentItems, reason: "pre-import")
            try storage.saveValidated(candidateItems)
            let loadedItems = try storage.loadResult().get().sorted { $0.lastCopiedAt > $1.lastCopiedAt }
            return (backupURL, loadedItems)
        }
        items = transactionResult.1
        storageErrorMessage = nil
        return transactionResult.0
    }

    @discardableResult
    func copy(_ item: ClipboardItem) -> Bool {
        guard !isTransferBusy else {
            return false
        }
        guard let index = items.firstIndex(where: { $0.id == item.id }) else {
            return false
        }

        let imageData: Data?
        if item.contentKind == .image {
            guard let storedImageData = storage.imageData(for: item) else {
                storageErrorMessage = "This image is missing from local storage and was not copied."
                return false
            }
            imageData = storedImageData
        } else {
            imageData = nil
        }

        let writeResult = writeToPasteboard(item, imageData: imageData)
        guard writeResult.wroteRequiredRepresentations else {
            storageErrorMessage = "The clip could not be written to the system clipboard."
            return false
        }
        if case let .degraded(optionalTypes) = writeResult {
            captureWarning = "The clip was copied without optional formats: \(optionalTypes.joined(separator: ", "))."
        }
        storageErrorMessage = nil

        var updated = items.remove(at: index)
        updated.lastCopiedAt = clock.now()
        updated.copyCount += 1
        items.insert(updated, at: 0)

        lastPasteboardChangeCount = pasteboard.changeCount
        lastCopiedID = updated.id

        pruneHistory()
        persist()
        clearCopiedIndicator(after: updated.id)
        return true
    }

    func copyWithTransformation(_ item: ClipboardItem, transformation: TextTransformation) {
        guard !isTransferBusy else { return }
        let transformedText = transformation.applied(to: item.text)
        guard !transformedText.isEmpty else {
            return
        }

        let result = pasteboardWriter.write(
            ClipboardPasteboardWriteRequest(
                required: [
                    ClipboardPasteboardRepresentation(.string, value: .string(transformedText))
                ],
                optional: []
            )
        )
        guard result.wroteRequiredRepresentations else {
            storageErrorMessage = "The transformed clip could not be written to the system clipboard."
            return
        }
        storageErrorMessage = nil
        lastPasteboardChangeCount = pasteboard.changeCount

        if let existingIndex = items.firstIndex(where: {
            $0.contentKind == .text && $0.text == transformedText
        }) {
            var existing = items.remove(at: existingIndex)
            existing.lastCopiedAt = clock.now()
            existing.copyCount += 1
            existing.sourceApplication = item.sourceApplication ?? existing.sourceApplication
            items.insert(existing, at: 0)
        } else {
            items.insert(
                ClipboardItem(text: transformedText, sourceApplication: item.sourceApplication),
                at: 0
            )
        }

        pruneHistory()
        persist()

        if let recordedItem = items.first, recordedItem.text == transformedText {
            lastCopiedID = recordedItem.id
            clearCopiedIndicator(after: recordedItem.id)
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard !isTransferBusy else { return }
        guard let index = items.firstIndex(where: { $0.id == item.id }) else {
            return
        }

        items[index].isPinned.toggle()
        pruneHistory()
        persist()
    }

    func delete(_ item: ClipboardItem) {
        guard !isTransferBusy else { return }
        items.removeAll { $0.id == item.id }
        flushPendingPersist()
    }

    func clearHistory() {
        guard !isTransferBusy else { return }
        invalidatePendingImageCaptures()
        if keepPinnedOnClear {
            items.removeAll { !$0.isPinned }
        } else {
            items.removeAll()
        }

        flushPendingPersist()
    }

    private func startMonitoring() {
        guard isMonitoringEnabled else { return }
        timer?.invalidate()

        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.pollPasteboardForChanges()
            }
        }

        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stopMonitoring() {
        timer?.invalidate()
        timer = nil
    }

    private func startPeriodicPruning() {
        pruneTimer?.invalidate()

        let timer = Timer(timeInterval: Self.pruneInterval, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.pruneHistoryAndPersistIfNeeded()
            }
        }

        RunLoop.main.add(timer, forMode: .common)
        self.pruneTimer = timer
    }

    func pollPasteboardForChanges(sourceApplicationOverride: ClipboardSourceApplication? = nil) {
        guard !isTransferBusy else {
            return
        }
        let currentChangeCount = pasteboard.changeCount

        guard currentChangeCount != lastPasteboardChangeCount else {
            return
        }

        lastPasteboardChangeCount = currentChangeCount

        guard !shouldIgnoreCurrentPasteboard() else {
            return
        }

        let sourceApplication = sourceApplicationOverride
            ?? (usesWorkspaceSourceTracking ? lastActiveApplication : sourceApplicationProvider())
        guard !isApplicationIgnored(sourceApplication) else {
            return
        }

        let capturedText = Self.capturedText(from: pasteboard)
        if let warning = capturedText.warning {
            captureWarning = warning
        }

        if let candidate = Self.imageCandidate(from: pasteboard) {
            let capturedAt = clock.now()
            processImageCandidate(
                candidate,
                associatedText: capturedText.snapshot,
                associatedWarning: capturedText.warning,
                sourceApplication: sourceApplication,
                capturedAt: capturedAt
            )
            return
        }

        guard let textSnapshot = capturedText.snapshot else {
            return
        }

        record(
            textSnapshot.text,
            rtfData: textSnapshot.rtfData,
            htmlData: textSnapshot.htmlData,
            sourceApplication: sourceApplication,
            capturedAt: clock.now()
        )
        captureWarning = capturedText.warning
    }

    private func shouldIgnoreCurrentPasteboard() -> Bool {
        guard let types = pasteboard.types else {
            return false
        }

        return types.contains { Self.ignoredPasteboardTypes.contains($0) }
    }

    private func processImageCandidate(
        _ candidate: ClipboardImageCandidate,
        associatedText: CapturedTextSnapshot?,
        associatedWarning: String?,
        sourceApplication: ClipboardSourceApplication?,
        capturedAt: Date
    ) {
        let queuedCapacity = Self.maximumPendingImageCaptures
            - (imageCaptureWorker == nil ? 0 : 1)
        while pendingImageCaptures.count >= max(queuedCapacity, 0),
              !pendingImageCaptures.isEmpty {
            pendingImageCaptures.removeFirst()
        }

        pendingImageCaptures.append(
            PendingImageCapture(
                candidate: candidate,
                associatedText: associatedText,
                associatedWarning: associatedWarning,
                sourceApplication: sourceApplication,
                capturedAt: capturedAt,
                generation: captureGeneration
            )
        )
        startImageCaptureWorkerIfNeeded()
    }

    private func startImageCaptureWorkerIfNeeded() {
        guard imageCaptureWorker == nil, !pendingImageCaptures.isEmpty else {
            return
        }
        let workerID = UUID()
        imageCaptureWorkerID = workerID
        imageCaptureWorker = Task { @MainActor [weak self] in
            await self?.drainImageCaptureQueue(workerID: workerID)
        }
    }

    private func drainImageCaptureQueue(workerID: UUID) async {
        defer {
            if imageCaptureWorkerID == workerID {
                imageCaptureWorker = nil
                imageCaptureWorkerID = nil
                startImageCaptureWorkerIfNeeded()
            }
        }

        while !Task.isCancelled, !pendingImageCaptures.isEmpty {
            let request = pendingImageCaptures.removeFirst()
            do {
                let image = try await imageProcessor.process(request.candidate)
                guard !Task.isCancelled,
                      captureGeneration == request.generation else {
                    continue
                }
                record(
                    image,
                    associatedText: request.associatedText?.text,
                    sourceApplication: request.sourceApplication,
                    capturedAt: request.capturedAt
                )
                captureWarning = request.associatedWarning
            } catch is CancellationError {
                return
            } catch {
                guard !Task.isCancelled,
                      captureGeneration == request.generation else {
                    continue
                }
                captureWarning = error.localizedDescription
                if let associatedText = request.associatedText {
                    record(
                        associatedText.text,
                        rtfData: associatedText.rtfData,
                        htmlData: associatedText.htmlData,
                        sourceApplication: request.sourceApplication,
                        capturedAt: request.capturedAt
                    )
                }
            }
        }
    }

    private func invalidatePendingImageCaptures() {
        captureGeneration &+= 1
        pendingImageCaptures.removeAll()
        imageCaptureWorker?.cancel()
        imageCaptureWorker = nil
        imageCaptureWorkerID = nil
    }

    nonisolated static func clearUnpinnedHistoryOnQuitIfNeeded(
        storage: ClipboardStorage = ClipboardStorage(),
        defaults: UserDefaults = .standard
    ) {
        guard defaults.bool(forKey: DefaultsKey.clearUnpinnedOnQuit) else {
            return
        }

        let itemsToKeep = itemsAfterQuitCleanup(storage.load())
        _ = try? storage.saveValidated(itemsToKeep)
    }

    func clearUnpinnedHistoryOnQuitIfNeeded() {
        invalidatePendingImageCaptures()
        guard clearUnpinnedOnQuit else {
            flushPendingPersist()
            return
        }

        items = Self.itemsAfterQuitCleanup(items)

        flushPendingPersist()
    }

    nonisolated private static func itemsAfterQuitCleanup(
        _ items: [ClipboardItem]
    ) -> [ClipboardItem] {
        items.filter(\.isPinned)
    }

    private func record(
        _ text: String,
        rtfData: Data? = nil,
        htmlData: Data? = nil,
        sourceApplication: ClipboardSourceApplication? = nil,
        capturedAt: Date? = nil
    ) {
        let capturedAt = capturedAt ?? clock.now()
        guard text.count <= ClipboardStorage.maximumImportedTextCharacters else {
            captureWarning = "A text clip was skipped because it exceeds 20,000 characters."
            return
        }

        guard text.rangeOfCharacter(from: .whitespacesAndNewlines.inverted) != nil else {
            return
        }

        if let existingIndex = items.firstIndex(where: {
            $0.contentKind == .text && $0.text == text
        }) {
            var existing = items.remove(at: existingIndex)
            let isNewestRepresentation = capturedAt >= existing.lastCopiedAt
            existing.lastCopiedAt = max(existing.lastCopiedAt, capturedAt)
            existing.copyCount += 1
            if isNewestRepresentation {
                existing.sourceApplication = sourceApplication ?? existing.sourceApplication
                existing.rtfData = rtfData
                existing.htmlData = htmlData
            }
            items.insert(existing, at: 0)
        } else {
            items.insert(
                ClipboardItem(text: text, rtfData: rtfData, htmlData: htmlData, sourceApplication: sourceApplication),
                at: 0
            )
        }

        pruneHistory()
        persist()
    }

    private func record(
        _ image: ClipboardImagePayload,
        associatedText: String? = nil,
        sourceApplication: ClipboardSourceApplication? = nil,
        capturedAt: Date? = nil
    ) {
        let capturedAt = capturedAt ?? clock.now()
        guard let data = image.data, data.count <= ClipboardImageProcessor.maximumEncodedBytes else {
            captureWarning = ClipboardImageProcessingError.encodedDataTooLarge.localizedDescription
            return
        }

        var storedImage = image
        if storedImage.contentHash == nil {
            storedImage.contentHash = ClipboardImageProcessor.contentHash(for: data)
        }

        if let existingIndex = items.firstIndex(where: { item in
            guard let existingHash = item.image?.contentHash,
                  let newHash = storedImage.contentHash else {
                return false
            }
            return existingHash == newHash
        }) {
            var existing = items.remove(at: existingIndex)
            let isNewestRepresentation = capturedAt >= existing.lastCopiedAt
            existing.lastCopiedAt = max(existing.lastCopiedAt, capturedAt)
            existing.copyCount += 1
            if isNewestRepresentation {
                existing.sourceApplication = sourceApplication ?? existing.sourceApplication
                existing.text = associatedText ?? ""
                existing.image = storedImage
            }
            items.insert(existing, at: 0)
        } else {
            items.insert(
                ClipboardItem(
                    text: associatedText ?? "",
                    image: storedImage,
                    createdAt: capturedAt,
                    lastCopiedAt: capturedAt,
                    sourceApplication: sourceApplication
                ),
                at: 0
            )
        }

        items.sort { $0.lastCopiedAt > $1.lastCopiedAt }
        pruneHistory()
        persist()
    }

    @discardableResult
    private func writeToPasteboard(
        _ item: ClipboardItem,
        imageData: Data?
    ) -> ClipboardPasteboardWriteResult {
        let request: ClipboardPasteboardWriteRequest
        switch item.contentKind {
        case .text:
            var optional: [ClipboardPasteboardRepresentation] = []
            if let rtfData = item.rtfData {
                optional.append(ClipboardPasteboardRepresentation(.rtf, value: .data(rtfData)))
            }
            if let htmlData = item.htmlData {
                optional.append(ClipboardPasteboardRepresentation(.html, value: .data(htmlData)))
            }
            request = ClipboardPasteboardWriteRequest(
                required: [
                    ClipboardPasteboardRepresentation(.string, value: .string(item.text))
                ],
                optional: optional
            )
        case .image:
            guard let imageData else {
                return .failure
            }
            var optional: [ClipboardPasteboardRepresentation] = []
            if !item.text.isEmpty {
                optional.append(
                    ClipboardPasteboardRepresentation(.string, value: .string(item.text))
                )
            }
            request = ClipboardPasteboardWriteRequest(
                required: [
                    ClipboardPasteboardRepresentation(.png, value: .data(imageData))
                ],
                optional: optional
            )
        }
        return pasteboardWriter.write(request)
    }

    private struct CapturedTextSnapshot {
        let text: String
        let rtfData: Data?
        let htmlData: Data?
    }

    private struct PendingImageCapture {
        let candidate: ClipboardImageCandidate
        let associatedText: CapturedTextSnapshot?
        let associatedWarning: String?
        let sourceApplication: ClipboardSourceApplication?
        let capturedAt: Date
        let generation: UInt64
    }

    private struct CapturedTextResult {
        let snapshot: CapturedTextSnapshot?
        let warning: String?
    }

    private static func capturedText(from pasteboard: NSPasteboard) -> CapturedTextResult {
        let rawRTFData = pasteboard.data(forType: .rtf)
        let rawHTMLData = pasteboard.data(forType: .html)
        let text = pasteboard.string(forType: .string)
            ?? attributedPlainText(data: rawRTFData, documentType: .rtf)
            ?? attributedPlainText(data: rawHTMLData, documentType: .html)

        guard let text else {
            return CapturedTextResult(snapshot: nil, warning: nil)
        }
        guard text.rangeOfCharacter(from: .whitespacesAndNewlines.inverted) != nil else {
            return CapturedTextResult(snapshot: nil, warning: nil)
        }
        guard text.count <= ClipboardStorage.maximumImportedTextCharacters else {
            return CapturedTextResult(
                snapshot: nil,
                warning: "A text clip was skipped because it exceeds 20,000 characters."
            )
        }

        let rtfData = rawRTFData.flatMap {
            $0.count <= ClipboardStorage.maximumImportedRichTextBytes ? $0 : nil
        }
        let htmlData = rawHTMLData.flatMap {
            $0.count <= ClipboardStorage.maximumImportedRichTextBytes ? $0 : nil
        }
        let droppedFormats = [
            rawRTFData != nil && rtfData == nil ? "RTF" : nil,
            rawHTMLData != nil && htmlData == nil ? "HTML" : nil
        ].compactMap { $0 }
        let warning = droppedFormats.isEmpty
            ? nil
            : "The text was saved without oversized \(droppedFormats.joined(separator: " and ")) formatting."
        return CapturedTextResult(
            snapshot: CapturedTextSnapshot(text: text, rtfData: rtfData, htmlData: htmlData),
            warning: warning
        )
    }

    private static func attributedPlainText(
        data: Data?,
        documentType: NSAttributedString.DocumentType
    ) -> String? {
        guard let data else { return nil }
        return try? NSAttributedString(
            data: data,
            options: [.documentType: documentType],
            documentAttributes: nil
        ).string
    }

    private static func imageCandidate(from pasteboard: NSPasteboard) -> ClipboardImageCandidate? {
        if let data = pasteboard.data(forType: .png) {
            return ClipboardImageCandidate(data: data, isPNG: true)
        }

        if let data = pasteboard.data(forType: .tiff) {
            return ClipboardImageCandidate(data: data, isPNG: false)
        }

        for type in [
            NSPasteboard.PasteboardType("public.jpeg"),
            NSPasteboard.PasteboardType("public.heic"),
            NSPasteboard.PasteboardType("public.heif")
        ] {
            if let data = pasteboard.data(forType: type) {
                return ClipboardImageCandidate(data: data, isPNG: false)
            }
        }

        if let fileURLString = pasteboard.string(forType: .fileURL),
           let fileURL = URL(string: fileURLString),
           fileURL.isFileURL,
           let resourceValues = try? fileURL.resourceValues(forKeys: [.fileSizeKey, .isRegularFileKey]),
           resourceValues.isRegularFile == true,
           resourceValues.fileSize ?? 0 <= ClipboardImageProcessor.maximumInputBytes,
           let data = try? Data(contentsOf: fileURL, options: [.mappedIfSafe]),
           ClipboardImageProcessor.isDecodableImage(data) {
            return ClipboardImageCandidate(data: data, isPNG: false)
        }

        return nil
    }

